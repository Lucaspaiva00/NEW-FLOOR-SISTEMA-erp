function textoVazio(valor: unknown): boolean {
  if (valor === null || valor === undefined) {
    return true;
  }

  return String(valor).trim() === "";
}

export function resolverObservacoesNaCriacao(body: {
  tipoProposta?: string;
  observacoes?: string | null;
  observacoesServicos?: string | null;
  observacoesSistema?: string | null;
}) {
  const tipoProposta = body.tipoProposta || "SERVICOS";

  if (tipoProposta === "SISTEMA") {
    if (!textoVazio(body.observacoesSistema) || !textoVazio(body.observacoes)) {
      const observacoesSistema =
        body.observacoesSistema ?? body.observacoes ?? null;

      return {
        observacoesServicos: body.observacoesServicos ?? null,
        observacoesSistema,
        observacoes: body.observacoes ?? observacoesSistema,
      };
    }

    return {
      observacoesServicos: body.observacoesServicos ?? null,
      observacoesSistema: formatarTextoObservacoes(OBSERVACOES_SISTEMA_PADRAO),
      observacoes: formatarTextoObservacoes(OBSERVACOES_SISTEMA_PADRAO),
    };
  }

  if (!textoVazio(body.observacoesServicos) || !textoVazio(body.observacoes)) {
    const observacoesServicos =
      body.observacoesServicos ?? body.observacoes ?? null;

    return {
      observacoesServicos,
      observacoesSistema: body.observacoesSistema ?? null,
      observacoes: body.observacoes ?? observacoesServicos,
    };
  }

  return {
    observacoesServicos: formatarTextoObservacoes(OBSERVACOES_SERVICOS_PADRAO),
    observacoesSistema: body.observacoesSistema ?? null,
    observacoes: formatarTextoObservacoes(OBSERVACOES_SERVICOS_PADRAO),
  };
}

